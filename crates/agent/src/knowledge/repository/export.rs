    #[test]
    fn stale_plans_are_refused_without_touching_the_target() {
        let fx = Fx::new();
        fx.put("src/a.rs", "pub fn a() {}\n");

        // The target appears after planning.
        let planned = plan(&fx, "generated/map.md");
        fx.put("generated/map.md", "someone else wrote this\n");
        let err = fx.service.apply_export(&planned).unwrap_err();
        assert_eq!(err.code(), "export_stale");
        assert_eq!(read(&fx, "generated/map.md"), "someone else wrote this\n");

        // The target's authored text changes after planning.
        fx.put("generated/doc.md", &format!("a\n{MAP_BEGIN}\n{MAP_END}\n"));
        let planned = plan(&fx, "generated/doc.md");
        let edited = format!("a edited\n{MAP_BEGIN}\n{MAP_END}\n");
        fx.put("generated/doc.md", &edited);
        let err = fx.service.apply_export(&planned).unwrap_err();
        assert_eq!(err.code(), "export_stale");
        assert_eq!(read(&fx, "generated/doc.md"), edited);

        // A fresh plan against the new bytes succeeds.
        fx.service
            .apply_export(&plan(&fx, "generated/doc.md"))
            .unwrap();
        assert!(read(&fx, "generated/doc.md").starts_with("a edited\n"));
    }

