//! Explicit, previewable export of a source map into a repository file.
//!
//! Indexing and map retrieval never write to the checkout. Exporting is a
//! separate, deliberate two-step operation:
//!
//! 1. [`RepositoryService::plan_export`] renders the map and works out exactly
//!    what the target file would become, without touching it. The plan records
//!    a *preimage*: the hash of the target's current bytes, or its absence.
//! 2. [`RepositoryService::apply_export`] re-reads the target, refuses if it no
//!    longer matches the preimage, and only then replaces it atomically.
//!
//! # One mechanism: the managed block
//!
//! The exported map always lives between two marker lines:
//!
//! ```markdown
//! <!-- qmt:map:begin -->
//! …generated map…
//! <!-- qmt:map:end -->
//! ```
//!
//! A *generated artifact* is simply a file that consists of such a block, so
//! "replace the artifact" and "replace the block inside an authored document"
//! are the same operation, and bytes outside the block are never rewritten.
//! A target that exists but has no unambiguous block is refused; the error says
//! how to pick a safe destination instead of overwriting prose.
//!
//! The markers are HTML comments, so other tools that read the file see an
//! ordinary Markdown section. Markers inside fenced code blocks are examples,
//! not delimiters.
//!
//! # Safety
//!
//! * Targets are repository-relative, never under `.git/` or `.agents/`, and
//!   no existing path component may be a symlink, so a write cannot leave the
//!   checkout.
//! * The write goes to a sibling temporary file that is renamed over the
//!   target, so readers see the old or the new file, never a partial one.
//! * The plan is built from [`render_map`](super::map::render_map), which is
//!   deterministic: equal sources export byte-identical files in any checkout.
//!   Nothing machine-local, no timestamps and no generation numbers are
//!   written.
//! * The file is not a filesystem snapshot guard against a hostile local
//!   writer racing between the preimage check and the rename; it protects
//!   against stale plans and accidental overwrites.

