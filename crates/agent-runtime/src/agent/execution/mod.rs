//! Core execution logic for the agent
//!
//! This module contains the run loop (`run_turn`, in `stage`) used by the kameo
//! `SessionActor` via `ctx.spawn()`. The implementation is split across focused
//! submodules:
//!
//! - `stage` — The loop position (`Stage`) and the function that moves it
//! - `transitions` — Step functions (before request, model call, after reply, tool calls)
//! - `tool_calls` — Tool execution, permission checking, and result storage
//! - `wait` — Event waiting and delegation completion handling
//! - `llm_retry` — LLM retry logic with rate limit handling
//! - `maintenance` — Pruning and AI compaction

fn format_stop_hook_continuation_message(
    reason: Option<String>,
    additional_contexts: &[String],
) -> String {
    let mut message =
        String::from("<system-reminder>\nA QueryMT Stop hook requested another agent step.\n");

    if let Some(reason) = reason.filter(|reason| !reason.trim().is_empty()) {
        message.push_str("\nReason:\n");
        message.push_str(&reason);
        message.push('\n');
    }

    if !additional_contexts.is_empty() {
        message.push_str("\nAdditional hook context:\n");
        for context in additional_contexts {
            message.push_str("- ");
            message.push_str(context);
            message.push('\n');
        }
    }

    message.push_str(
        "\nThis message was generated by the QueryMT hook runtime, not by the user.\n</system-reminder>",
    );
    message
}

